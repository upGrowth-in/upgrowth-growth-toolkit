#!/usr/bin/env node
// Copies skills/<name>/** into the SKILL_FILES block of src/worker.mjs.
// The Worker is a single file with its data inlined, so skills are inlined too.
// Run after editing anything under skills/:  node scripts/sync-skills.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const skillsDir = join(root, 'skills');
const workerPath = join(root, 'src', 'worker.mjs');

const walk = (dir) => readdirSync(dir).sort().flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

export function collectSkillFiles() {
  const files = {};
  for (const p of walk(skillsDir)) files['skill://' + relative(skillsDir, p).split(sep).join('/')] = readFileSync(p, 'utf8');
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const block = '// SKILLS:BEGIN (generated by scripts/sync-skills.mjs from skills/, do not edit by hand)\n'
    + 'const SKILL_FILES = ' + JSON.stringify(collectSkillFiles(), null, 2) + ';\n// SKILLS:END';
  const src = readFileSync(workerPath, 'utf8');
  const re = /\/\/ SKILLS:BEGIN[\s\S]*?\/\/ SKILLS:END/;
  if (!re.test(src)) throw new Error('SKILLS block markers not found in src/worker.mjs');
  writeFileSync(workerPath, src.replace(re, () => block));
  console.log('Synced ' + Object.keys(collectSkillFiles()).length + ' skill file(s) into src/worker.mjs');
}
